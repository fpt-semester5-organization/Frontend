export type ErrorCode = keyof typeof ERROR_CODES;

export const ERROR_HTTP_STATUS: Record<ErrorCode, number> = Object.fromEntries(
  Object.entries(ERROR_CODES).map(([k, v]) => [k, v.http])
) as Record<ErrorCode, number>;

export const ERROR_MESSAGES: Record<ErrorCode, string> = Object.fromEntries(
  Object.entries(ERROR_CODES).map(([k, v]) => [k, v.message])
) as Record<ErrorCode, string>;

export const isKnownErrorCode = (code: string): code is ErrorCode => code in ERROR_CODES;

export const errorMessage = (code?: string, fallback = 'Đã xảy ra lỗi, vui lòng thử lại.') =>
  code && isKnownErrorCode(code) ? ERROR_CODES[code].message : fallback;
